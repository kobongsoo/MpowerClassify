#------------------------------------------------------------------
# HWPX 문단 단위 추출 테스트 — Rust 판과 같은 규칙인가
#=> HWPX 는 글자 서식이 바뀌는 자리에서 <hp:t> 를 갈라 놓는다. 태그마다 줄을
#   끊으면 한 낱말이 쪼개지고("가치를" → "가치" / "를"), 붙어 있어야 성립하는
#   검출(전화·계좌번호, 앵커+값)이 통째로 어긋난다.
#
#   Rust 판(Rust/crates/docparse/src/extract.rs)에 같은 이름의 시험이 있고 기대값이 같다.
#   한쪽만 고치면 두 판의 본문이 조용히 어긋나 등급이 갈린다.
#------------------------------------------------------------------

from csoclassify.extract.hwpx_zip import _collect_paragraphs


#------------------------------------------------------------------
# 섹션 XML 을 문단 줄 목록으로 (테스트 도우미)
#
# -in: xml = section XML 조각
#
# -out: list[str] = 문단마다 한 줄
# -out: error = 없음
#------------------------------------------------------------------
def _lines(xml):
    out = []
    _collect_paragraphs(xml, out)
    return out


#------------------------------------------------------------------
# 한 문단은 한 줄로 이어진다
#=> 서식이 바뀌어 <hp:t> 가 갈라져도 낱말이 쪼개지면 안 된다.
#
# -in: 없음
# -out: 없음(assert)
# -out: error = 실패 시 AssertionError
#------------------------------------------------------------------
def test_hwpx_한_문단은_한_줄로_이어진다():
    xml = ('<hp:p id="1"><hp:run><hp:t>가치</hp:t></hp:run>'
           '<hp:run><hp:t>를 보장한다</hp:t></hp:run></hp:p>'
           '<hp:p id="2"><hp:run><hp:t>다음 문단</hp:t></hp:run></hp:p>')
    assert _lines(xml) == ["가치를 보장한다", "다음 문단"]


#------------------------------------------------------------------
# 표 안의 문단도 제 줄을 갖는다
#=> HWPX 는 문단이 문단 안에 들어간다(hp:p > hp:tbl > hp:tc > hp:subList > hp:p).
#   짝 맞추기 방식이면 바깥 여는 태그와 안쪽 닫는 태그를 짝지어 경계가 엉킨다.
#   칸마다 제 줄을 갖고, 글자는 문서에 적힌 차례대로 남아야 한다.
#
# -in: 없음
# -out: 없음(assert)
# -out: error = 실패 시 AssertionError
#------------------------------------------------------------------
def test_hwpx_표_안의_문단도_제_줄을_갖는다():
    xml = ('<hp:p id="1"><hp:run><hp:t>표 앞 글</hp:t></hp:run>'
           '<hp:run><hp:tbl><hp:tr>'
           '<hp:tc><hp:subList><hp:p><hp:run><hp:t>왼쪽 칸</hp:t></hp:run>'
           '</hp:p></hp:subList></hp:tc>'
           '<hp:tc><hp:subList><hp:p><hp:run><hp:t>오른쪽 칸</hp:t></hp:run>'
           '</hp:p></hp:subList></hp:tc>'
           '</hp:tr></hp:tbl></hp:run></hp:p>')
    assert _lines(xml) == ["표 앞 글", "왼쪽 칸", "오른쪽 칸"]


#------------------------------------------------------------------
# 문단 안 줄바꿈·탭을 살린다
#=> 없애면 두 줄이 한 낱말로 붙어 문서에 없던 말("끝다음")이 생긴다.
#
# -in: 없음
# -out: 없음(assert)
# -out: error = 실패 시 AssertionError
#------------------------------------------------------------------
def test_hwpx_줄바꿈과_탭을_살린다():
    xml = ('<hp:p><hp:run><hp:t>끝</hp:t><hp:lineBreak/><hp:t>다음</hp:t>'
           '<hp:tab/><hp:t>칸</hp:t></hp:run></hp:p>')
    assert _lines(xml) == ["끝\n다음\t칸"]


#------------------------------------------------------------------
# 빈 문단은 줄을 만들지 않는다
#=> HWPX 는 빈 문단을 여백으로 쓴다. 줄로 만들면 빈 줄만 쌓인다.
#
# -in: 없음
# -out: 없음(assert)
# -out: error = 실패 시 AssertionError
#------------------------------------------------------------------
def test_hwpx_빈_문단은_줄을_만들지_않는다():
    xml = ('<hp:p><hp:run><hp:t>글</hp:t></hp:run></hp:p>'
           '<hp:p/><hp:p><hp:run><hp:t>  </hp:t></hp:run></hp:p>'
           '<hp:p><hp:run><hp:t>다음</hp:t></hp:run></hp:p>')
    assert _lines(xml) == ["글", "다음"]


#------------------------------------------------------------------
# 자기닫힘 <hp:p/> 도 문단 경계로 본다
#=> 자기닫힘 갈래를 여는 태그 갈래보다 뒤에 두면, 여는 쪽이 끝의 '/' 를 속성으로
#   삼켜 경계를 놓친다. 그러면 앞뒤 문단이 한 줄로 붙어 없던 낱말이 생긴다.
#
# -in: 없음
# -out: 없음(assert)
# -out: error = 실패 시 AssertionError
#------------------------------------------------------------------
def test_hwpx_자기닫힘_문단도_경계로_본다():
    xml = ('<hp:p><hp:run><hp:t>앞</hp:t></hp:run></hp:p>'
           '<hp:p id="x"/>'
           '<hp:p><hp:run><hp:t>뒤</hp:t></hp:run></hp:p>')
    assert _lines(xml) == ["앞", "뒤"]
